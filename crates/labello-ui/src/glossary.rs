//! Canonical product vocabulary shared by every UI renderer.
//! See `docs/glossary.md` for meanings, compatibility names, and usage rules.

/// A product term or action. Contextual prose may explain its effect further.
pub struct Entry {
    pub name: &'static str,
    pub definition: &'static str,
}

macro_rules! glossary {
    ($($id:ident => ($name:literal, $definition:literal),)*) => {
        $(pub const $id: &str = $name;)*
        pub const ENTRIES: &[Entry] = &[
            $(Entry { name: $name, definition: $definition },)*
        ];
    };
}

