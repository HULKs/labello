/// Canonical annotation type name for selectors and configuration summaries.
pub(crate) fn annotation_type_name(kind: &labello_domain::AnnotationType) -> &'static str {
    match kind {
        labello_domain::AnnotationType::BoundingBox => BOUNDING_BOX,
        labello_domain::AnnotationType::Skeleton => SKELETON,
    }
}
